import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { cpus, platform, release } from 'node:os';
import { performance } from 'node:perf_hooks';
import { NodeIO } from '@gltf-transform/core';
import { KHRDracoMeshCompression, EXTTextureWebP } from '@gltf-transform/extensions';
import draco3d from 'draco3dgltf';
import sharp from 'sharp';
import { createFixture } from './fixture.mjs';
import { optimizeAsset } from '../src/optimizer.mjs';

const temporaryRoot = fileURLToPath(new URL('../.tmp/', import.meta.url));
await mkdir(temporaryRoot, { recursive: true });
const directory = await mkdtemp(join(temporaryRoot, 'benchmark-'));
const source = await createFixture(join(directory, 'original.glb'));
const timings = {};
async function optimize(name, options) {
  const start = performance.now();
  const manifest = await optimizeAsset({ output: join(directory, name), ...options });
  timings[name] = performance.now() - start;
  return manifest;
}
const geometry = await optimize('draco', { source });
const embedded = await optimize('embedded-webp', { source, embeddedWebp: true });
const image = await optimize('image', { source: join(directory, 'source.png'), imagePolicy: 'detail' });
const photoPixels = Buffer.alloc(512 * 256 * 3);
for (let y = 0; y < 256; y++) for (let x = 0; x < 512; x++) {
  const index = (y * 512 + x) * 3;
  photoPixels[index] = Math.floor(x / 2);
  photoPixels[index + 1] = y;
  photoPixels[index + 2] = Math.floor((Math.sin(x / 16) + 1) * 80);
}
const photoSource = join(directory, 'photo.jpg');
await writeFile(photoSource, await sharp(photoPixels, { raw: { width: 512, height: 256, channels: 3 } }).jpeg({ quality: 100 }).toBuffer());
const photo = await optimize('photo', { source: photoSource, imagePolicy: 'photo' });
const alphaSource = join(directory, 'alpha.png');
await writeFile(alphaSource, await sharp({ create: { width: 128, height: 128, channels: 4, background: { r: 31, g: 93, b: 147, alpha: 0.4 } } }).png().toBuffer());
const alpha = await optimize('alpha', { source: alphaSource, imagePolicy: 'detail' });
const codec = new NodeIO().registerExtensions([KHRDracoMeshCompression, EXTTextureWebP]).registerDependencies({ 'draco3d.decoder': await draco3d.createDecoderModule() });
const decode = [];
for (const [name, path] of [['original', source], ...geometry.artifacts.map((artifact) => [artifact.file, join(directory, 'draco', artifact.file)])]) {
  const bytes = await readFile(path);
  await codec.readBinary(bytes);
  const samples = [];
  let document;
  for (let run = 0; run < 5; run++) {
    const start = performance.now();
    document = await codec.readBinary(bytes);
    samples.push(performance.now() - start);
  }
  const arrays = new Set(document.getRoot().listAccessors().map((accessor) => accessor.getArray()));
  decode.push({ name, milliseconds: samples, medianMs: [...samples].sort((a, b) => a - b)[2], decodedAccessorBytes: [...arrays].reduce((total, array) => total + array.byteLength, 0), method: 'NodeIO readBinary, decoder initialized, one warmup then five sequential runs, in-memory bytes' });
}
const report = { dataset: { name: 'Synthetic UV sphere and mathematical image gradients', rights: 'CC0, generated by package fixture code', limitations: 'Single synthetic asset. Museum inscriptions, thin/glossy/transparent artifacts, mobile/WebXR and human fidelity review remain unverified.' }, environment: { node: process.version, os: `${platform()} ${release()}`, cpu: cpus()[0]?.model, logicalCpus: cpus().length }, status: 'REVIEW_REQUIRED', wallTimeMs: timings, timingMethod: 'Observed single processing invocation per variant on this machine; background load uncontrolled.', geometry, embedded, image, photo, alpha, decode, runtimeMetrics: { download: 'UNAVAILABLE', firstVisible: 'UNAVAILABLE', fps: 'UNAVAILABLE', gpuMemory: 'UNAVAILABLE', jsHeap: 'UNAVAILABLE' } };
const path = join(directory, 'benchmark.json');
await writeFile(path, `${JSON.stringify(report, null, 2)}\n`);
process.stdout.write(`${path}\n`);
